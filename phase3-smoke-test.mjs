import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const art = path.join(here, 'art');
const html = fs.readFileSync(path.join(art, 'index.html'), 'utf8');
const css = fs.readFileSync(path.join(art, 'styles.css'), 'utf8');
const js = fs.readFileSync(path.join(art, 'app.js'), 'utf8');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
assert.equal(ids.length, new Set(ids).size, 'Art Studio HTML IDs must be unique');
for (const id of ['ageGate','confirmAge','artGrid','poseGrid','creatorForm','promptOutput','savedGrid','detailModal','poseModal']) assert.ok(ids.includes(id), `Missing required HTML id: ${id}`);
for (const tab of ['gallery','poses','creator','saved']) assert.ok(html.includes(`data-tab="${tab}"`), `Missing ${tab} tab`);
assert.match(html, /artflip-figure-index\.js/, '52-record open-access index must load');
assert.match(html, /Art-v2-\/#creator-section/, 'Existing Creator integration link must exist');
assert.match(js, /isPublicDomain === true/, 'Museum index must be filtered to public-domain records');
assert.match(js, /localStorage\.setItem\(ART_KEY/, 'Saved shelf must be local-only');
assert.match(js, /std_P001_front\.webp/, 'Pose Atlas must include Shisei CC0 references');
assert.match(js, /std_P070_below\.webp/, 'Pose Atlas must include the eight-set library');
assert.equal((js.match(/std_P\d{3}_[a-z]+\.webp/g) || []).length >= 32, true, 'Expected at least 32 pose-angle references');
assert.match(css, /prefers-reduced-motion/, 'Reduced-motion support is required');
assert.match(html, /viewport-fit=cover/, 'Mobile viewport support is required');
assert.doesNotMatch(js, /fetch\s*\(|XMLHttpRequest|WebSocket/, 'The Art Studio itself must not send app data to a backend');
for (const id of [...js.matchAll(/\$\('([^']+)'\)/g)].map(m => m[1])) assert.ok(ids.includes(id), `JS references missing HTML id: ${id}`);
const poseRefs = [...js.matchAll(/std_P\d{3}_[a-z]+\.webp/g)].map(m => m[0]);
console.log(`PASS: ${ids.length} unique IDs, ${poseRefs.length} pose reference mentions, 4 tabs, remote ArtFlip index, local Saved shelf, Creator route and responsive accessibility hooks.`);
